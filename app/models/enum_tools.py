# enum_tools.py
# Contain code to generate enumerated types from source json file to be used with models.py in defining shared features across climbing gyms.

import json
from enum import Enum
import re

def clean_values_for_enums(value: str):
    """Convert value from json to appropriate format for enum: all upper, special char and whitespace -> underscore"""
    return re.sub(r'[ \-\(\)]', '_', value.upper())

def generate_enums(json_file, output_file):
    """Generate Python Enums from a JSON file."""
    with open(json_file, "r") as f:
        data = json.load(f)

    def write_preamble():
        f.write(f'# app/models/enums.py\n')
        f.write(f'# Contains enumerated types to be used with app/models in defining shared features across climbing gyms\n')
        f.write(f'# This module is updated and autogenerated by enum_tools.py\n\n')
        f.write(f'from enum import Enum, auto\n')
        f.write(f'\n')

    def register_base_enum():
        f.write(f'class BaseEnum(Enum):\n')
        f.write(f'\t# Base class to represent all other enums requiring simple custom string representation\n')
        f.write(f'\tdef __str__(self):\n')
        f.write(f'\t\t# Return custom string representation\n')
        f.write(f'\t\t# TEST_ENUM.name --> Test Enum\n')
        f.write(f'\t\treturn self.name.replace("_", " ").title()\n')
        f.write(f'\n')

    def write_enum_name(name: str):
        f.write(f"class {name}(BaseEnum):\n")

    def write_enum_value(enum_name: str, enum_value: str='auto()\n'):
        cleaned_name = clean_values_for_enums(enum_name)
        f.write(f'\t{cleaned_name} = {enum_value}')

    def write_basic_enum_type(enum_name:str, values: list[str], comment: str):
        write_enum_name(enum_name)
        f.write(f'\t# {comment}\n')
        for item in values:
            write_enum_value(item)
        f.write(f'\n')

    def register_franchisers(values: list[str]):
        write_basic_enum_type(enum_name='eFranchiser', values=values, comment='Register climbing gym franchisers')

    def register_gym_status(values: list[str]):
        write_basic_enum_type(enum_name='eGymStatus', values=values, comment='Register climbing gym status')

    def register_climbing_activities(values: list[str]):
        write_basic_enum_type(enum_name='eClimbActivities', values=values, comment='Register climbing activities offerd')

    def register_board_climbing():
        board_brands = ['Kilter board', 'MoonBoard', 'Tension board','Tension board 2', 'Circuit board', 'Wave board', 'Spray wall', 'Grasshopper board', 'Unknown RGB board', 'Unknown Wooden board']
        write_basic_enum_type(enum_name='eClimbBoard', values=board_brands, comment='Register climbing boards')

    def register_locker_types(values: list[str]):
        write_basic_enum_type(enum_name='eLockerTypes', values=values, comment='Register gym locker types')

    def register_grading_system(values: list[str]):
        write_basic_enum_type(enum_name='eGradingSystem', values=values, comment='Register route grading system')

    def register_mat_hire(values: list[str]):
        write_basic_enum_type(enum_name='eMatHire', values=values, comment='Register outdoor mat hire availability')

    with open(output_file, "w") as f:
        write_preamble()
        register_base_enum()
        for key, values in data['_dropdown_options'].items():
            if key == 'Franchiser':
                register_franchisers(values)
            elif key == 'Status':
                register_gym_status(values)
            elif key == 'Climbing offered':
                register_climbing_activities(values)
            elif key == 'Lockers':
                register_locker_types(values)
            elif key == 'Board climbing':
                register_board_climbing()
            elif key == 'Grading system':
                register_grading_system(values)
            elif key == 'Mat hire':
                register_mat_hire(values)
            else:
                f.write(f'# WIP: {key}\n')


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Generate Enums from JSON.")
    parser.add_argument("json_file", help="Path to the JSON file.")
    parser.add_argument("output_file", help="Path to the output Python file.")
    args = parser.parse_args()

    generate_enums(args.json_file, args.output_file)